    w = random.choice(tech_words)
    pat = random.randint(1, 7)
    if pat == 1:
        sent = f"{subj} {adv} {verb}."
    elif pat == 2:
        sent = f"{subj} {w} {verb}."
    elif pat == 3:
        sent = f"{adv} {subj} {verb}."
